"""Generate/check factual TK040F1510 register ROM and independent bench words.

The input is the supplied vendor's ordered address/data list, not executable C.
No PDF, archive, vendor source or binary is copied into the source tree.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
PROFILE = ROOT / 'docs/hardware/tk040f1510_profile.json'
ROM = ROOT / 'rtl/nt35510_init_rom.sv'
CANONICAL_SHA256 = 'baf2de274f52d2be53a7d936088736ecbb17d2159b3b6edf9ffcb4043fdc4aca'
SUPPORTED_CONTRACT = {
    'bus': dict(data_bits=8, command_word_bits=16, parameter_word_bits=16,
                word_byte_order='most-significant byte first', pixel_format='RGB565',
                pixel_write_bytes=2),
    'orientation': dict(width=800, height=480, madctl='0x00A3',
                        pixel_format_register='0x0055'),
    'wait_policy': dict(clock_hz=100000000, reset_low_ms=20, reset_release_wait_ms=120,
                        sleep_out_wait_ms=120, sleep_out_wait_after_command='0x1100',
                        source_loop_delay_is_milliseconds=False),
    'source': dict(archive_sha256='8702c3d9530f01eb264423371c8b1c04697b468f0044fee70c543b2047450bf2',
                   entry_sha256='56656bfe4c7d893b932cecce9ed49d4c352e262e3077ec6a1b291f82ef733fdd'),
}


def validate_contract(profile):
    """This audited profile describes fixed RTL, not configurable bus hardware.

    Checking register pairs alone would accept a profile claiming a 16-bit bus,
    reversed byte order or different waits while generating the same 8-bit ROM.
    Reject such metadata drift, including JSON booleans used as numeric values.
    """
    if not isinstance(profile, dict) or type(profile.get('schema_version')) is not int \
            or profile['schema_version'] != 1:
        raise ValueError('unsupported screen profile schema')
    for section, fields in SUPPORTED_CONTRACT.items():
        actual = profile.get(section)
        if not isinstance(actual, dict):
            raise ValueError('missing screen profile contract: ' + section)
        for name, expected in fields.items():
            value = actual.get(name)
            if type(value) is not type(expected) or value != expected:
                raise ValueError(f'unsupported screen profile contract: {section}.{name}')


def load_profile(path=PROFILE):
    profile = json.loads(Path(path).read_text(encoding='utf-8'))
    validate_contract(profile)
    entries = profile.get('entries')
    if not isinstance(entries, list) or len(entries) != 367:
        raise ValueError('canonical profile requires exactly 367 entries')
    rows = []
    previous_line = 0
    for index, entry in enumerate(entries):
        if not isinstance(entry, dict):
            raise ValueError(f'entry {index} must be a JSON object')
        if entry.get('index') != index:
            raise ValueError('initialization indices must be contiguous')
        values = []
        for name in ('command', 'data'):
            value = entry.get(name)
            if name == 'data' and value is None:
                values.append(None)
            elif isinstance(value, str) and re.fullmatch(r'0x[0-9A-Fa-f]{4}', value):
                values.append(int(value, 16))
            else:
                raise ValueError(f'entry {index} has invalid 16-bit {name}')
        line = entry.get('source_line')
        if not isinstance(line, int) or line <= previous_line:
            raise ValueError('source line references must increase')
        previous_line = line
        rows.append(tuple(values))
    digest = hashlib.sha256(json.dumps(rows, separators=(',', ':')).encode('ascii')).hexdigest()
    if digest != CANONICAL_SHA256 or profile.get('canonical_pairs_sha256') != digest:
        raise ValueError('initialization differs from the audited canonical vendor values')
    actual = dict(rom_entries=len(rows), register_writes=sum(d is not None for _, d in rows),
                  command_only=sum(d is None for _, d in rows),
                  word_transfers=sum(1 + (d is not None) for _, d in rows))
    actual['bus_write_bytes'] = actual['word_transfers'] * 2
    if profile.get('counts') != actual:
        raise ValueError('profile transfer counts do not match its entries')
    return profile, rows


def render_rom(profile, rows):
    lines = ['`timescale 1ns/1ps',
             '// Generated by scripts/generate_nt35510_rom.py; do not edit by hand.',
             '// Canonical source LCD.c SHA256: ' + profile['source']['entry_sha256'],
             '// Values are facts transcribed from the supplied TK040F1510 vendor sample.',
             'module nt35510_init_rom(',
             '  input wire [8:0] index,output reg [15:0] command,data,',
             '  output reg has_data,sleep_wait,last',
             ');',
             '  localparam integer ENTRY_COUNT=367;',
             '  always @*begin',
             "    command=16'd0;data=16'd0;has_data=0;sleep_wait=0;last=0;",
             '    case(index)']
    for index, (command, data) in enumerate(rows):
        fields = [f"command=16'h{command:04X};"]
        if data is not None:
            fields += [f"data=16'h{data:04X};", "has_data=1'b1;"]
        if command == 0x1100:
            fields.append("sleep_wait=1'b1;")
        if index == len(rows) - 1:
            fields.append("last=1'b1;")
        lines.append(f"      9'd{index}:begin {''.join(fields)} end // LCD.c:{profile['entries'][index]['source_line']}")
    lines += ['      default:begin end', '    endcase', '  end', 'endmodule', '']
    return '\n'.join(lines)


def export_expected(path, profile, rows):
    """Flatten source facts directly; the bench never reads DUT ROM outputs."""
    path = Path(path)
    path.mkdir(parents=True, exist_ok=True)
    words = []
    for command, data in rows:
        words.append(command)
        if data is not None:
            words.append(0x10000 | data)
    data = ''.join(f'{word:05x}\n' for word in words)
    target = path / 'expected_init.hex'
    if target.exists() and target.read_text(encoding='ascii') != data:
        raise ValueError('refusing to overwrite different expected initialization evidence')
    target.write_text(data, encoding='ascii', newline='\n')
    manifest = dict(word_count=len(words), bus_write_bytes=2 * len(words),
                    sleep_out_word_index=words.index(0x1100),
                    canonical_pairs_sha256=CANONICAL_SHA256,
                    expected_words_sha256=hashlib.sha256(data.encode('ascii')).hexdigest(),
                    source=profile['source'])
    (path / 'expected_init.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n',
                                           encoding='utf-8', newline='\n')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--profile', type=Path, default=PROFILE)
    parser.add_argument('--output', type=Path, default=ROM)
    parser.add_argument('--expected-dir', type=Path)
    args = parser.parse_args(argv)
    try:
        profile, rows = load_profile(args.profile)
        expected = render_rom(profile, rows).encode('utf-8')
        if args.check:
            if args.output.read_bytes() != expected:
                raise ValueError('generated ROM is stale or differs from the profile')
        else:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_bytes(expected)
        if args.expected_dir:
            export_expected(args.expected_dir, profile, rows)
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f'FAIL NT35510 ROM: {error}', file=sys.stderr)
        return 1
    print('PASS NT35510 ROM: 367 entries / 732 words / 1464 bus bytes')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
